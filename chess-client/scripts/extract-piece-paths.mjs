// Turn the twelve chess glyphs of Noto Sans Symbols 2 into plain outlines the
// PDF export can draw.
//
// Why not embed the font: pdf-lib's subsetter silently drops glyphs from it —
// exported diagrams came out with no kings and no white pawns — and embedding
// the whole 640 KB font in every exported page to use twelve glyphs is worse
// than carrying their outlines as data. Drawing paths also means the figurines
// in the move text and the pieces on the diagrams come from one source.
//
// Run from chess-client/ when the source font changes:
//   node scripts/extract-piece-paths.mjs
import fontkit from "@pdf-lib/fontkit";
import { readFileSync, writeFileSync } from "fs";

const SOURCE = "src/assets/fonts/NotoSansSymbols2-Regular.ttf";
const TARGET = "src/lib/pieceOutlines.ts";
const PIECES = {
  K: 0x2654, Q: 0x2655, R: 0x2656, B: 0x2657, N: 0x2658, P: 0x2659,
  k: 0x265a, q: 0x265b, r: 0x265c, b: 0x265d, n: 0x265e, p: 0x265f,
};

const font = fontkit.create(readFileSync(SOURCE));
const entries = Object.entries(PIECES).map(([piece, codePoint]) => {
  const glyph = font.glyphForCodePoint(codePoint);
  // PDF draws SVG paths with y pointing down; font outlines point up, so the
  // outline is flipped here once rather than at every draw.
  const path = glyph.path.scale(1, -1).toSVG();
  if (!path) throw new Error(`no outline for ${piece} (U+${codePoint.toString(16)})`);
  return `  ${piece === piece.toLowerCase() ? `"${piece}"` : piece}: "${path}",`;
});

writeFileSync(TARGET, `// GENERATED by scripts/extract-piece-paths.mjs — do not edit by hand.
//
// The twelve chess pieces as outlines, taken from Noto Sans Symbols 2
// (SIL Open Font License 1.1; see src/assets/fonts/NotoSansSymbols2-LICENSE.txt).
// Upper case is White, lower case Black, as in a FEN. Coordinates are in font
// units with the y axis pointing DOWN from the baseline (as PDF draws them),
// ${font.unitsPerEm} to the em.

export const PIECE_UNITS_PER_EM = ${font.unitsPerEm};

/** Drawn on a ${font.unitsPerEm}-unit em square with the baseline at y = 0;
 *  a piece occupies roughly y = -${font.unitsPerEm * 0.75} to y = 0. Upper case is the
 *  outlined White piece, lower case the filled Black one — draw the lower-case
 *  outline in white first to make either opaque on a dark square. */
export const PIECE_OUTLINES: Record<string, string> = {
${entries.join("\n")}
};
`);
console.log(`${TARGET}: ${entries.length} outlines`);
